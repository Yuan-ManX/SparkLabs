class CreativeGoalGenerator:
    """Generates creative goals from detected gameplay patterns.

    Each pattern type maps to one or more creative goal types. The generator
    prioritizes goals based on pattern confidence, player state, and the
    historical effectiveness of similar goals.
    """

    # Pattern -> Goal type mapping
    PATTERN_GOAL_MAP = {
        PatternType.ENGAGEMENT_DECLINE: [
            CreativeGoalType.NARRATIVE_EVENT,
            CreativeGoalType.ENVIRONMENTAL_SHIFT,
            CreativeGoalType.INTRODUCE_MECHANIC,
        ],
        PatternType.DIFFICULTY_FLATLINE: [
            CreativeGoalType.DIFFICULTY_CURVE,
            CreativeGoalType.PROGRESSION_GATE,
        ],
        PatternType.CONTENT_STAGNATION: [
            CreativeGoalType.INTRODUCE_MECHANIC,
            CreativeGoalType.REVEAL_CONTENT,
            CreativeGoalType.ENVIRONMENTAL_SHIFT,
        ],
        PatternType.SKILL_PLATEAU: [
            CreativeGoalType.PROGRESSION_GATE,
            CreativeGoalType.DIFFICULTY_CURVE,
        ],
        PatternType.REPETITIVE_BEHAVIOR: [
            CreativeGoalType.INTRODUCE_MECHANIC,
            CreativeGoalType.REVEAL_CONTENT,
        ],
        PatternType.NARRATIVE_GAP: [
            CreativeGoalType.NARRATIVE_EVENT,
            CreativeGoalType.SOCIAL_DYNAMIC,
        ],
        PatternType.UNEXPLORED_REGION: [
            CreativeGoalType.REVEAL_CONTENT,
            CreativeGoalType.ENVIRONMENTAL_SHIFT,
        ],
        PatternType.MASTERY_SURPLUS: [
            CreativeGoalType.DIFFICULTY_CURVE,
            CreativeGoalType.PROGRESSION_GATE,
        ],
    }

    # Goal descriptions
    GOAL_DESCRIPTIONS = {
        CreativeGoalType.INTRODUCE_MECHANIC: "Introduce a new gameplay mechanic to refresh engagement",
        CreativeGoalType.NARRATIVE_EVENT: "Trigger a narrative event to advance the story",
        CreativeGoalType.DIFFICULTY_CURVE: "Reshape the difficulty curve for better pacing",
        CreativeGoalType.REVEAL_CONTENT: "Reveal hidden or unexplored content",
        CreativeGoalType.SOCIAL_DYNAMIC: "Introduce an NPC interaction or faction event",
        CreativeGoalType.ENVIRONMENTAL_SHIFT: "Transform the environment dynamically",
        CreativeGoalType.PROGRESSION_GATE: "Create a meaningful progression checkpoint",
    }

    def __init__(self) -> None:
        self._creative_memory: Dict[str, CreativePattern] = {}
        self._goal_history: Deque[CreativeGoal] = deque(maxlen=50)

    def generate(
        self,
        patterns: List[GameplayPattern],
        session_id: str = "",
    ) -> List[CreativeGoal]:
        """Generate creative goals from detected patterns."""
        goals: List[CreativeGoal] = []

        for pattern in patterns:
            goal_types = self.PATTERN_GOAL_MAP.get(pattern.pattern_type, [])
            for goal_type in goal_types:
                # Check if we already have an active goal of this type
                if any(g.goal_type == goal_type and g.status in (
                    GoalStatus.PROPOSED, GoalStatus.PLANNING, GoalStatus.EXECUTING
                ) for g in goals):
                    continue

                # Calculate priority based on pattern confidence and past effectiveness
                base_priority = pattern.confidence * 0.6
                past_effect = self._get_past_effectiveness(goal_type, pattern.pattern_type)
                priority = min(1.0, base_priority + past_effect * 0.3)

                goal = CreativeGoal(
                    goal_type=goal_type,
                    trigger_pattern=pattern.pattern_type,
                    description=self.GOAL_DESCRIPTIONS.get(goal_type, ""),
                    priority=priority,
                    target_session_id=session_id,
                    predicted_impact=self._predict_impact(goal_type, pattern),
                )
                goals.append(goal)

        # Sort by priority
        goals.sort(key=lambda g: g.priority, reverse=True)
        return goals

    def _get_past_effectiveness(
        self,
        goal_type: CreativeGoalType,
        trigger: PatternType,
    ) -> float:
        """Get the historical effectiveness of a goal type for a trigger."""
        key = f"{goal_type.value}:{trigger.value}"
        pattern = self._creative_memory.get(key)
        return pattern.effectiveness if pattern else 0.3

    def _predict_impact(
        self,
        goal_type: CreativeGoalType,
        pattern: GameplayPattern,
    ) -> Dict[str, float]:
        """Predict the impact of a creative intervention."""
        # Base predictions on goal type
        predictions = {
            "engagement_delta": 0.0,
            "variety_delta": 0.0,
            "difficulty_delta": 0.0,
        }

        if goal_type == CreativeGoalType.INTRODUCE_MECHANIC:
            predictions["engagement_delta"] = 0.2
            predictions["variety_delta"] = 0.3
        elif goal_type == CreativeGoalType.NARRATIVE_EVENT:
            predictions["engagement_delta"] = 0.15
            predictions["variety_delta"] = 0.2
        elif goal_type == CreativeGoalType.DIFFICULTY_CURVE:
            predictions["difficulty_delta"] = 0.15
            predictions["engagement_delta"] = 0.1
        elif goal_type == CreativeGoalType.REVEAL_CONTENT:
            predictions["engagement_delta"] = 0.1
            predictions["variety_delta"] = 0.25
        elif goal_type == CreativeGoalType.ENVIRONMENTAL_SHIFT:
            predictions["engagement_delta"] = 0.15
            predictions["variety_delta"] = 0.2
        elif goal_type == CreativeGoalType.PROGRESSION_GATE:
            predictions["engagement_delta"] = 0.1
            predictions["difficulty_delta"] = 0.1
        elif goal_type == CreativeGoalType.SOCIAL_DYNAMIC:
            predictions["engagement_delta"] = 0.12
            predictions["variety_delta"] = 0.15

        # Modulate by pattern confidence
        for k in predictions:
            predictions[k] *= pattern.confidence

        return predictions

    def record_outcome(self, goal: CreativeGoal) -> None:
        """Record the outcome of a creative goal for future learning."""
        self._goal_history.append(goal)
        key = f"{goal.goal_type.value}:{goal.trigger_pattern.value}"
        current = self._creative_memory.get(key)
        if current is None:
            current = CreativePattern(
                goal_type=goal.goal_type,
                trigger_pattern=goal.trigger_pattern,
                effectiveness=goal.effectiveness,
                use_count=1,
                last_used=time.time(),
            )
        else:
            # Exponential moving average
            alpha = 0.3
            current.effectiveness = alpha * goal.effectiveness + (1 - alpha) * current.effectiveness
            current.use_count += 1
            current.last_used = time.time()
        self._creative_memory[key] = current

    def get_memory_stats(self) -> List[Dict[str, Any]]:
        """Get creative memory statistics."""
        return [
            {
                "goal_type": p.goal_type.value,
                "trigger": p.trigger_pattern.value,
                "effectiveness": round(p.effectiveness, 3),
                "use_count": p.use_count,
            }
            for p in self._creative_memory.values()
        ]


