class CreativeAutonomyDirector:
    """
    The singleton director that orchestrates proactive creative intelligence
    during live gameplay. It monitors long-term patterns, generates creative
    goals, plans multi-step interventions, and learns from outcomes.

    This is the creative counterpart to the BridgeOrchestrator (reactive)
    and the AgentEngineFusionLoop (engine optimization). Together, the three
    form the complete AI-native agent intelligence:

    - BridgeOrchestrator: per-frame reactive adaptation
    - AgentEngineFusionLoop: engine performance optimization
    - CreativeAutonomyDirector: proactive creative content generation
    """

    _instance: Optional["CreativeAutonomyDirector"] = None
    _instance_lock = threading.Lock()

    def __init__(self) -> None:
        self._lock = threading.RLock()
        self._pattern_monitor = GameplayPatternMonitor()
        self._goal_generator = CreativeGoalGenerator()
        self._intervention_planner = InterventionPlanner()

        # Active state
        self._active_goals: Dict[str, CreativeGoal] = {}
        self._completed_goals: Deque[CreativeGoal] = deque(maxlen=50)
        self._last_pattern_check: float = 0.0
        self._pattern_check_interval_s: float = 10.0  # Check patterns every 10s
        self._last_intervention_check: float = 0.0
        self._intervention_check_interval_s: float = 2.0  # Check interventions every 2s

        # Statistics
        self._total_patterns_detected: int = 0
        self._total_goals_generated: int = 0
        self._total_interventions_planned: int = 0
        self._total_steps_executed: int = 0
        self._total_successful_goals: int = 0
        self._total_abandoned_goals: int = 0

        # Session tracking
        self._session_id: str = ""
        self._snapshot_count: int = 0

    @classmethod
    def get_instance(cls) -> "CreativeAutonomyDirector":
        if cls._instance is None:
            with cls._instance_lock:
                if cls._instance is None:
                    cls._instance = cls()
        return cls._instance

    # -------------------------------------------------------------------------
    # Public API
    # -------------------------------------------------------------------------

    def record_gameplay_snapshot(
        self,
        engagement: float,
        difficulty: float,
        variety: float,
        exploration: float,
        events: List[str],
        session_id: str = "",
    ) -> None:
        """Record a periodic gameplay snapshot for pattern detection.

        Call this every 5-10 seconds from the bridge or game loop.
        """
        with self._lock:
            self._session_id = session_id or self._session_id
            self._pattern_monitor.record_snapshot(
                engagement, difficulty, variety, exploration, events
            )
            self._snapshot_count += 1

    def check_and_generate(self) -> List[CreativeGoal]:
        """Check for patterns and generate creative goals if needed.

        Returns any newly generated goals. Call this periodically.
        """
        with self._lock:
            now = time.time()
            if now - self._last_pattern_check < self._pattern_check_interval_s:
                return []

            self._last_pattern_check = now

            # Detect patterns
            patterns = self._pattern_monitor.detect_patterns()
            self._total_patterns_detected += len(patterns)

            if not patterns:
                return []

            # Generate goals
            new_goals = self._goal_generator.generate(patterns, self._session_id)
            self._total_goals_generated += len(new_goals)

            # Plan interventions for new goals
            for goal in new_goals:
                goal.intervention_steps = self._intervention_planner.plan_intervention(goal)
                goal.status = GoalStatus.PLANNING
                self._total_interventions_planned += len(goal.intervention_steps)
                self._active_goals[goal.goal_id] = goal

            return new_goals

    def get_pending_steps(self, session_id: str = "") -> List[Tuple[str, InterventionStep]]:
        """Get intervention steps that are ready to execute.

        Returns a list of (goal_id, step) tuples for steps whose delay
        has elapsed and haven't been executed yet.
        """
        with self._lock:
            now = time.time()
            pending: List[Tuple[str, InterventionStep]] = []

            for goal in list(self._active_goals.values()):
                if goal.status not in (GoalStatus.PLANNING, GoalStatus.EXECUTING):
                    continue

                goal.status = GoalStatus.EXECUTING
                steps = goal.intervention_steps

                for i, step in enumerate(steps):
                    if step.executed:
                        continue
                    if i < goal.current_step_index:
                        continue

                    # Check delay
                    if i == 0:
                        ready = True
                    else:
                        prev_step = steps[i - 1]
                        if prev_step.executed:
                            ready = now - prev_step.executed_at >= step.delay_s
                        else:
                            ready = False

                    if ready:
                        pending.append((goal.goal_id, step))
                        goal.current_step_index = i
                        break  # One step per goal per check

            return pending

    def mark_step_executed(
        self,
        goal_id: str,
        step_id: str,
        result: Dict[str, Any],
    ) -> None:
        """Mark an intervention step as executed."""
        with self._lock:
            goal = self._active_goals.get(goal_id)
            if not goal:
                return

            for step in goal.intervention_steps:
                if step.step_id == step_id:
                    step.executed = True
                    step.executed_at = time.time()
                    step.result = result
                    self._total_steps_executed += 1
                    break

            # Check if all steps are complete
            if all(s.executed for s in goal.intervention_steps):
                goal.status = GoalStatus.EVALUATING

    def evaluate_goal(self, goal_id: str, impact: Dict[str, float]) -> None:
        """Evaluate the outcome of a completed creative goal."""
        with self._lock:
            goal = self._active_goals.get(goal_id)
            if not goal:
                return

            goal.actual_impact = impact

            # Calculate effectiveness as average of predicted vs actual alignment
            if goal.predicted_impact:
                total_delta = 0.0
                count = 0
                for key, predicted in goal.predicted_impact.items():
                    actual = impact.get(key, 0.0)
                    if predicted > 0:
                        # Positive prediction: effectiveness = actual / predicted
                        total_delta += min(1.0, actual / predicted) if predicted > 0 else 0.0
                    else:
                        # No prediction: use actual directly
                        total_delta += min(1.0, max(0.0, actual))
                    count += 1
                goal.effectiveness = total_delta / count if count > 0 else 0.0
            else:
                # No predictions: use average of actual impacts
                vals = [v for v in impact.values() if isinstance(v, (int, float))]
                goal.effectiveness = sum(vals) / len(vals) if vals else 0.0

            # Mark goal as successful or abandoned
            if goal.effectiveness > 0.2:
                goal.status = GoalStatus.SUCCESSFUL
                self._total_successful_goals += 1
            else:
                goal.status = GoalStatus.ABANDONED
                self._total_abandoned_goals += 1

            # Record in creative memory
            self._goal_generator.record_outcome(goal)

            # Move to completed
            self._completed_goals.append(goal)
            del self._active_goals[goal_id]

    def status(self) -> Dict[str, Any]:
        """Get the creative autonomy director status."""
        with self._lock:
            return {
                "session_id": self._session_id,
                "snapshot_count": self._snapshot_count,
                "active_goals": len(self._active_goals),
                "completed_goals": len(self._completed_goals),
                "total_patterns_detected": self._total_patterns_detected,
                "total_goals_generated": self._total_goals_generated,
                "total_interventions_planned": self._total_interventions_planned,
                "total_steps_executed": self._total_steps_executed,
                "total_successful_goals": self._total_successful_goals,
                "total_abandoned_goals": self._total_abandoned_goals,
                "success_rate": (
                    self._total_successful_goals / max(1, self._total_successful_goals + self._total_abandoned_goals)
                ),
                "creative_memory": self._goal_generator.get_memory_stats(),
            }

    def get_active_goals(self) -> List[Dict[str, Any]]:
        """Get currently active creative goals."""
        with self._lock:
            return [
                {
                    "goal_id": g.goal_id,
                    "goal_type": g.goal_type.value,
                    "trigger_pattern": g.trigger_pattern.value,
                    "description": g.description,
                    "priority": round(g.priority, 3),
                    "status": g.status.value,
                    "current_step": g.current_step_index,
                    "total_steps": len(g.intervention_steps),
                    "predicted_impact": g.predicted_impact,
                    "effectiveness": round(g.effectiveness, 3),
                    "steps": [
                        {
                            "step_id": s.step_id,
                            "phase": s.phase.value,
                            "action_type": s.action_type,
                            "params": s.params,
                            "delay_s": s.delay_s,
                            "executed": s.executed,
                        }
                        for s in g.intervention_steps
                    ],
                }
                for g in self._active_goals.values()
            ]

    def get_completed_goals(self, limit: int = 20) -> List[Dict[str, Any]]:
        """Get recently completed creative goals."""
        with self._lock:
            goals = list(self._completed_goals)[-limit:]
        return [
            {
                "goal_id": g.goal_id,
                "goal_type": g.goal_type.value,
                "trigger_pattern": g.trigger_pattern.value,
                "description": g.description,
                "status": g.status.value,
                "effectiveness": round(g.effectiveness, 3),
                "predicted_impact": g.predicted_impact,
                "actual_impact": g.actual_impact,
            }
            for g in goals
        ]

    def reset(self) -> None:
        """Reset the creative autonomy director state."""
        with self._lock:
            self._pattern_monitor = GameplayPatternMonitor()
            self._goal_generator = CreativeGoalGenerator()
            self._intervention_planner = InterventionPlanner()
            self._active_goals.clear()
            self._completed_goals.clear()
            self._total_patterns_detected = 0
            self._total_goals_generated = 0
            self._total_interventions_planned = 0
            self._total_steps_executed = 0
            self._total_successful_goals = 0
            self._total_abandoned_goals = 0
            self._snapshot_count = 0
            self._session_id = ""


