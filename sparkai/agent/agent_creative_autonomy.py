class CreativeGoalType(Enum):
    """Types of creative goals the director can generate."""
    INTRODUCE_MECHANIC = "introduce_mechanic"
    NARRATIVE_EVENT = "narrative_event"
    DIFFICULTY_CURVE = "difficulty_curve"
    REVEAL_CONTENT = "reveal_content"
    SOCIAL_DYNAMIC = "social_dynamic"
    ENVIRONMENTAL_SHIFT = "environmental_shift"
    PROGRESSION_GATE = "progression_gate"


class PatternType(Enum):
    """Detected gameplay patterns that trigger creative goals."""
    ENGAGEMENT_DECLINE = "engagement_decline"
    DIFFICULTY_FLATLINE = "difficulty_flatline"
    CONTENT_STAGNATION = "content_stagnation"
    UNEXPLORED_REGION = "unexplored_region"
    SKILL_PLATEAU = "skill_plateau"
    REPETITIVE_BEHAVIOR = "repetitive_behavior"
    NARRATIVE_GAP = "narrative_gap"
    MASTERY_SURPLUS = "mastery_surplus"
    NONE = "none"


class InterventionPhase(Enum):
    """Phases of a multi-step intervention."""
    SETUP = "setup"
    BUILDUP = "buildup"
    CLIMAX = "climax"
    RESOLUTION = "resolution"
    COMPLETE = "complete"


class GoalStatus(Enum):
    """Status of a creative goal."""
    PROPOSED = "proposed"
    PLANNING = "planning"
    EXECUTING = "executing"
    EVALUATING = "evaluating"
    SUCCESSFUL = "successful"
    ABANDONED = "abandoned"


