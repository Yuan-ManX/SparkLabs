# Data Structures
# =============================================================================

@dataclass
class GameplayPattern:
    """A detected gameplay pattern over a time window."""
    pattern_id: str = field(default_factory=lambda: uuid.uuid4().hex[:10])
    pattern_type: PatternType = PatternType.NONE
    confidence: float = 0.0
    duration_s: float = 0.0
    evidence: Dict[str, float] = field(default_factory=dict)
    detected_at: float = field(default_factory=time.time)
    description: str = ""


@dataclass
class CreativeGoal:
    """A proactive creative goal generated by the autonomy director."""
    goal_id: str = field(default_factory=lambda: uuid.uuid4().hex[:10])
    goal_type: CreativeGoalType = CreativeGoalType.NARRATIVE_EVENT
    trigger_pattern: PatternType = PatternType.NONE
    description: str = ""
    priority: float = 0.5
    created_at: float = field(default_factory=time.time)
    status: GoalStatus = GoalStatus.PROPOSED
    intervention_steps: List["InterventionStep"] = field(default_factory=list)
    current_step_index: int = 0
    predicted_impact: Dict[str, float] = field(default_factory=dict)
    actual_impact: Dict[str, float] = field(default_factory=dict)
    effectiveness: float = 0.0
    target_session_id: str = ""


@dataclass
class InterventionStep:
    """A single step in a multi-step intervention plan."""
    step_id: str = field(default_factory=lambda: uuid.uuid4().hex[:8])
    phase: InterventionPhase = InterventionPhase.SETUP
    action_type: str = ""       # spawn_entity, trigger_event, tune_difficulty, etc.
    params: Dict[str, Any] = field(default_factory=dict)
    delay_s: float = 0.0        # delay after previous step
    executed: bool = False
    executed_at: float = 0.0
    result: Optional[Dict[str, Any]] = None


@dataclass
class CreativePattern:
    """A learned creative pattern that was effective in the past."""
    pattern_id: str = field(default_factory=lambda: uuid.uuid4().hex[:10])
    goal_type: CreativeGoalType = CreativeGoalType.NARRATIVE_EVENT
    trigger_pattern: PatternType = PatternType.NONE
    effectiveness: float = 0.0
    use_count: int = 0
    last_used: float = 0.0
    context_tags: List[str] = field(default_factory=list)


