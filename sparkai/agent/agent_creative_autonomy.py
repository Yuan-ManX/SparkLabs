class GameplayPatternMonitor:
    """Monitors long-term gameplay patterns across minutes of play.

    Collects periodic gameplay snapshots and detects patterns that indicate
    creative opportunities. Unlike the BridgeOrchestrator which works per-frame,
    this works on a longer timescale (every 5-10 seconds).
    """

    def __init__(self) -> None:
        self._engagement_timeline: Deque[Tuple[float, float]] = deque(maxlen=60)
        self._difficulty_timeline: Deque[Tuple[float, float]] = deque(maxlen=60)
        self._variety_timeline: Deque[Tuple[float, float]] = deque(maxlen=60)
        self._exploration_timeline: Deque[Tuple[float, float]] = deque(maxlen=60)
        self._event_diversity: Deque[set] = deque(maxlen=60)
        self._last_snapshot_time: float = 0.0

    def record_snapshot(
        self,
        engagement: float,
        difficulty: float,
        variety: float,
        exploration: float,
        events: List[str],
    ) -> None:
        """Record a periodic gameplay snapshot (call every 5-10s)."""
        now = time.time()
        self._engagement_timeline.append((now, engagement))
        self._difficulty_timeline.append((now, difficulty))
        self._variety_timeline.append((now, variety))
        self._exploration_timeline.append((now, exploration))
        self._event_diversity.append(set(events))
        self._last_snapshot_time = now

    def detect_patterns(self) -> List[GameplayPattern]:
        """Detect gameplay patterns from the collected timeline data."""
        patterns: List[GameplayPattern] = []

        if len(self._engagement_timeline) < 6:
            return patterns  # Not enough data

        # Check for engagement decline
        eng_decline = self._check_engagement_decline()
        if eng_decline:
            patterns.append(eng_decline)

        # Check for difficulty flatline
        diff_flat = self._check_difficulty_flatline()
        if diff_flat:
            patterns.append(diff_flat)

        # Check for content stagnation (low event variety)
        stagnation = self._check_content_stagnation()
        if stagnation:
            patterns.append(stagnation)

        # Check for skill plateau (high skill but low engagement growth)
        skill_plate = self._check_skill_plateau()
        if skill_plate:
            patterns.append(skill_plate)

        # Check for repetitive behavior
        repetitive = self._check_repetitive_behavior()
        if repetitive:
            patterns.append(repetitive)

        # Check for narrative gap (no events for a long time)
        narrative = self._check_narrative_gap()
        if narrative:
            patterns.append(narrative)

        # Check for unexplored region
        unexplored = self._check_unexplored_region()
        if unexplored:
            patterns.append(unexplored)

        return patterns

    def _check_engagement_decline(self) -> Optional[GameplayPattern]:
        """Check if engagement is declining over time."""
        if len(self._engagement_timeline) < 10:
            return None
        recent = [e for _, e in list(self._engagement_timeline)[-5:]]
        older = [e for _, e in list(self._engagement_timeline)[-10:-5]]
        recent_avg = sum(recent) / len(recent)
        older_avg = sum(older) / len(older)
        if recent_avg < older_avg - 0.1 and recent_avg < 0.5:
            return GameplayPattern(
                pattern_type=PatternType.ENGAGEMENT_DECLINE,
                confidence=min(1.0, (older_avg - recent_avg) * 3),
                duration_s=50.0,
                evidence={"recent_avg": recent_avg, "older_avg": older_avg, "delta": recent_avg - older_avg},
                description=f"Engagement declining: {older_avg:.2f} -> {recent_avg:.2f}",
            )
        return None

    def _check_difficulty_flatline(self) -> Optional[GameplayPattern]:
        """Check if difficulty has been flat for too long."""
        if len(self._difficulty_timeline) < 8:
            return None
        recent = [d for _, d in list(self._difficulty_timeline)[-8:]]
        variance = max(recent) - min(recent)
        if variance < 0.05:
            return GameplayPattern(
                pattern_type=PatternType.DIFFICULTY_FLATLINE,
                confidence=min(1.0, (0.1 - variance) * 10),
                duration_s=40.0,
                evidence={"variance": variance, "avg": sum(recent) / len(recent)},
                description=f"Difficulty flat for 8+ samples (variance={variance:.3f})",
            )
        return None

    def _check_content_stagnation(self) -> Optional[GameplayPattern]:
        """Check if event variety is low."""
        if len(self._event_diversity) < 6:
            return None
        recent_sets = list(self._event_diversity)[-6:]
        all_events = set()
        for s in recent_sets:
            all_events |= s
        if len(all_events) < 3:
            return GameplayPattern(
                pattern_type=PatternType.CONTENT_STAGNATION,
                confidence=min(1.0, (3 - len(all_events)) * 0.4),
                duration_s=30.0,
                evidence={"unique_events": len(all_events), "events": list(all_events)},
                description=f"Low event variety: only {len(all_events)} unique events",
            )
        return None

    def _check_skill_plateau(self) -> Optional[GameplayPattern]:
        """Check if player skill has plateaued."""
        if len(self._difficulty_timeline) < 10:
            return None
        recent_diff = [d for _, d in list(self._difficulty_timeline)[-5:]]
        avg_diff = sum(recent_diff) / len(recent_diff)
        if avg_diff > 0.7:
            return GameplayPattern(
                pattern_type=PatternType.SKILL_PLATEAU,
                confidence=0.6,
                duration_s=25.0,
                evidence={"avg_difficulty": avg_diff},
                description="Player skill high but no new challenges introduced",
            )
        return None

    def _check_repetitive_behavior(self) -> Optional[GameplayPattern]:
        """Check if player is repeating the same actions."""
        if len(self._event_diversity) < 5:
            return None
        recent_sets = list(self._event_diversity)[-5:]
        # Check if the same single event dominates
        all_events = []
        for s in recent_sets:
            all_events.extend(list(s))
        if len(all_events) > 0:
            from collections import Counter
            counts = Counter(all_events)
            most_common_ratio = counts.most_common(1)[0][1] / len(all_events)
            if most_common_ratio > 0.7:
                return GameplayPattern(
                    pattern_type=PatternType.REPETITIVE_BEHAVIOR,
                    confidence=most_common_ratio,
                    duration_s=25.0,
                    evidence={"dominant_event": counts.most_common(1)[0][0], "ratio": most_common_ratio},
                    description=f"Repetitive behavior: {counts.most_common(1)[0][0]} dominates",
                )
        return None

    def _check_narrative_gap(self) -> Optional[GameplayPattern]:
        """Check if there's been a lack of narrative events."""
        if len(self._event_diversity) < 4:
            return None
        recent_sets = list(self._event_diversity)[-4:]
        has_narrative = any("narrative" in e or "story" in e or "dialogue" in e for s in recent_sets for e in s)
        if not has_narrative:
            return GameplayPattern(
                pattern_type=PatternType.NARRATIVE_GAP,
                confidence=0.5,
                duration_s=20.0,
                evidence={"has_narrative": False},
                description="No narrative events detected in recent play",
            )
        return None

    def _check_unexplored_region(self) -> Optional[GameplayPattern]:
        """Check if exploration radius has stagnated."""
        if len(self._exploration_timeline) < 6:
            return None
        recent = [e for _, e in list(self._exploration_timeline)[-3:]]
        older = [e for _, e in list(self._exploration_timeline)[-6:-3]]
        recent_avg = sum(recent) / len(recent)
        older_avg = sum(older) / len(older)
        if abs(recent_avg - older_avg) < 10 and recent_avg < 500:
            return GameplayPattern(
                pattern_type=PatternType.UNEXPLORED_REGION,
                confidence=0.4,
                duration_s=30.0,
                evidence={"exploration_radius": recent_avg},
                description="Player not expanding exploration radius",
            )
        return None


